/**
 * Declares the AsciiDoc document model (IKE-Network/ike-issues#468): the primitives a parse
 * of an IKE AsciiDoc document — a Kompendium or lab topic written to the fragment standard —
 * produces, as the meanings and patterns a knowledge graph needs to hold such a document
 * line for line with its provenance, and the git-provenance apparatus the materialization
 * from a repository stamps it with.
 *
 * <p><b>The inventory is measured, not imagined.</b> Over the 1,037 lab and ANF topics of
 * 2026-10-12 every document carries the header comments, the four topic attributes, a block
 * anchor and a level-1 title; 813 have sections, 297 tables, 180 listings, 142 diagram
 * blocks, 301 and 184 unordered and ordered lists; 1,008 carry {@code indexterm:[]} and 426
 * flow index terms, 349 cross-reference other topics, 109 cite bibliography entries, 21 carry
 * footnotes. Inline formatting (bold, italic, monospace, highlights, roles) is text and stays
 * in the line verbatim; it declares no meaning here. What a parse does not understand becomes
 * an opaque block, so no document is ever refused.
 *
 * <p><b>The line is the unit of provenance.</b> A document's lines are prose elements
 * ({@link ProseElementSet}), one per line under semantic line breaks, ordered by the journal
 * manifest; a STAMP per git commit says who introduced each. The structural elements —
 * sections, blocks, lists, tables — are the ones a conversation journal shares
 * ({@link DocumentStructureSet}, IKE-Network/ike-issues#844), grouping lines through the
 * document block pattern's members field; this section adds the blocks only AsciiDoc has.
 * The inline references — index terms, cross references, citations, footnotes, links,
 * estimate marks — are semantics on the line they occur in, regenerated by every parse.
 *
 * <p><b>Two modules.</b> The model root, the module concept and the git-provenance family
 * stamp in the foundation module, so a store that leaves the AsciiDoc module out still
 * navigates to the family; every AsciiDoc element, field, purpose and pattern stamps in the
 * AsciiDoc document module ({@link Ike#ASCIIDOC_INCEPTION}), the export dimension that carries
 * or omits the document vocabulary as a unit. Documents themselves stamp under the git
 * modules the identity adapter derives per repository, never here.
 */
final class AsciiDocModelSet {

    static final String MODULE_FQN = "AsciiDoc document module (IkeFoundation)";
    static final String ROOT_FQN = "AsciiDoc document model (IkeFoundation)";

    private static final EntityProxy.Concept MODULE_SOLOR =
            EntityProxy.Concept.make("Module (SOLOR)", PublicIds.of("40d1c869-b509-32f8-b735-836eac577a67"));
    private static final EntityProxy.Concept PATH_SOLOR =
            EntityProxy.Concept.make("Path (SOLOR)", PublicIds.of("4459d8cf-5a6f-3952-9458-6d64324b27b7"));
    private static final EntityProxy.Concept IKE_BASE_MODEL_CONCEPT =
            EntityProxy.Concept.make("IKE base model concept", PublicIds.of("bc59d656-83d3-47d8-9507-0e656ea95463"));

    private AsciiDocModelSet() {
    }

    /**
     * Composes this section's declarations into the session.
     *
     * @param set the knowledge set (the session)
     */
    static void compose(KnowledgeSet set) {
        ActiveStamp foundation = Ike.INCEPTION;
        ActiveStamp asciidoc = Ike.ASCIIDOC_INCEPTION;

        // ── Apparatus in the foundation module: the module, the family root ──────
        set.concept(MODULE_FQN).at(foundation)
                .synonym("AsciiDoc document module")
                .definition("The module scoping the AsciiDoc document vocabulary: every element,"
                        + " field, purpose and pattern of the AsciiDoc document model stamps its"
                        + " versions here, and this module holds nothing else. As the export"
                        + " dimension it carries or omits the document vocabulary as a unit."
                        + " Documents materialized from a repository stamp under that repository's"
                        + " own module, never here.")
                .isA(MODULE_SOLOR);
        set.concept(ROOT_FQN).at(foundation)
                .synonym("AsciiDoc document model")
                .definition("The primitives a parse of an IKE AsciiDoc document produces — the"
                        + " elements, the inline references, the composition directives, and the"
                        + " fields their patterns carry — so a knowledge graph holds a document"
                        + " line for line with its provenance and gives it back unchanged.")
                .isA(IKE_BASE_MODEL_CONCEPT);

        // ── Elements ─────────────────────────────────────────────────────────────
        element(set, asciidoc, "AsciiDoc element", ROOT_FQN,
                "Anything a parse of an AsciiDoc document yields that Markdown does not share: a"
                        + " document with topic attributes, an inline reference, or a composition"
                        + " directive. Sections and blocks are document elements, and the"
                        + " AsciiDoc-only blocks are document blocks; a document's lines are prose"
                        + " elements, one per line, which those elements group and annotate.");
        set.concept(fqn("AsciiDoc document")).at(asciidoc)
                .synonym("AsciiDoc document")
                .definition("A whole AsciiDoc document — a topic — as the anchor its lines, blocks,"
                        + " references and attributes hang from; named by its topic id, else its"
                        + " path.")
                .isA(set.conceptRef(fqn("AsciiDoc element")),
                        set.conceptRef(DocumentStructureSet.fqn("Structured document")));
        element(set, asciidoc, "AsciiDoc literal block", DocumentStructureSet.fqn("Document block"),
                "A .... delimited literal block: text rendered as it is.");
        element(set, asciidoc, "AsciiDoc example block", DocumentStructureSet.fqn("Document block"),
                "A ==== delimited example block.");
        element(set, asciidoc, "AsciiDoc sidebar block", DocumentStructureSet.fqn("Document block"),
                "A **** delimited sidebar.");
        element(set, asciidoc, "AsciiDoc open block", DocumentStructureSet.fqn("Document block"),
                "A -- delimited open block: an anonymous container that takes its kind from its"
                        + " parameters, as an [anf] block does.");
        element(set, asciidoc, "AsciiDoc admonition block", DocumentStructureSet.fqn("Document block"),
                "A NOTE, TIP, WARNING, IMPORTANT or CAUTION, as a paragraph or a delimited block;"
                        + " the kind is in its parameters.");
        element(set, asciidoc, "AsciiDoc diagram block", DocumentStructureSet.fqn("Document block"),
                "A [plantuml] or [graphviz] block whose source lines are its members; the tool,"
                        + " the diagram name and the output format are in its parameters.");
        element(set, asciidoc, "AsciiDoc bibliography entry", DocumentStructureSet.fqn("Document block"),
                "One [[[key]]] entry of a [bibliography] list, the target of citations.");

        element(set, asciidoc, "AsciiDoc inline reference", fqn("AsciiDoc element"),
                "A reference that occurs inside a line and points beyond it: an index term, a"
                        + " cross reference, a citation, a footnote, a link, an estimate mark."
                        + " It is a semantic on the line it occurs in, regenerated by every parse.");
        element(set, asciidoc, "AsciiDoc index term reference", fqn("AsciiDoc inline reference"),
                "An index term — indexterm:[a, b], a flow ((term)) or a concealed (((term))) —"
                        + " resolved where possible to the concept it names.");
        element(set, asciidoc, "AsciiDoc cross reference", fqn("AsciiDoc inline reference"),
                "An xref:target[text] or <<target>> to a topic or section anchor.");
        element(set, asciidoc, "AsciiDoc citation", fqn("AsciiDoc inline reference"),
                "A <<key>> citation of a bibliography entry.");
        element(set, asciidoc, "AsciiDoc footnote", fqn("AsciiDoc inline reference"),
                "A footnote:[text] on a line.");
        element(set, asciidoc, "AsciiDoc link", fqn("AsciiDoc inline reference"),
                "A link: macro or bare URL on a line.");
        element(set, asciidoc, "AsciiDoc estimate mark", fqn("AsciiDoc inline reference"),
                "The mark a claim carries when its figure is the authors' own estimate, open to"
                        + " revision — provenance a reader must see.");

        element(set, asciidoc, "AsciiDoc composition", fqn("AsciiDoc element"),
                "A directive that composes documents rather than saying anything: an include or"
                        + " a conditional.");
        element(set, asciidoc, "AsciiDoc include", fqn("AsciiDoc composition"),
                "An include:: of another document or file, as an assembly composes topics.");
        element(set, asciidoc, "AsciiDoc conditional", fqn("AsciiDoc composition"),
                "An ifdef:: or ifndef:: guard on an attribute, closed by endif::.");

        // ── Fields and purposes ──────────────────────────────────────────────────
        field(set, asciidoc, "AsciiDoc field", ROOT_FQN,
                "A field of an AsciiDoc document pattern.");
        field(set, asciidoc, "AsciiDoc term text", fqn("AsciiDoc field"),
                "An index term's text as written, primary and secondary terms comma-separated.");
        field(set, asciidoc, "AsciiDoc referenced concept", fqn("AsciiDoc field"),
                "The concept an index term resolved to, when it did.");
        field(set, asciidoc, "AsciiDoc reference target", fqn("AsciiDoc field"),
                "The anchor, path or URL a reference, include or link points at, as written.");
        field(set, asciidoc, "AsciiDoc reference text", fqn("AsciiDoc field"),
                "The display text of a cross reference or link, empty when the target's own"
                        + " title is used.");
        field(set, asciidoc, "AsciiDoc citation key", fqn("AsciiDoc field"),
                "The bibliography key a citation names.");
        field(set, asciidoc, "AsciiDoc referenced entry", fqn("AsciiDoc field"),
                "The bibliography entry a citation resolved to, when it did.");
        field(set, asciidoc, "AsciiDoc footnote text", fqn("AsciiDoc field"),
                "A footnote's text.");
        field(set, asciidoc, "AsciiDoc attribute name", fqn("AsciiDoc field"),
                "The attribute a conditional tests.");
        field(set, asciidoc, "AsciiDoc negated", fqn("AsciiDoc field"),
                "Whether a conditional is ifndef rather than ifdef.");
        field(set, asciidoc, "AsciiDoc document title", fqn("AsciiDoc field"),
                "The document's level-1 title.");
        field(set, asciidoc, "Topic id", fqn("AsciiDoc field"),
                "The :topic-id: attribute: the topic's registry key and block anchor.");
        field(set, asciidoc, "Topic type", fqn("AsciiDoc field"),
                "The :topic-type: attribute: concept, task, reference, or another registry type.");
        field(set, asciidoc, "Topic status", fqn("AsciiDoc field"),
                "The :topic-status: attribute: draft, review, published, or another registry"
                        + " status.");
        field(set, asciidoc, "Topic keywords", fqn("AsciiDoc field"),
                "The :topic-keywords: attribute, comma-separated.");
        field(set, asciidoc, "Topic scope note", fqn("AsciiDoc field"),
                "The :topic-scope-note: attribute, with its continued lines joined.");
        field(set, asciidoc, "Topic license", fqn("AsciiDoc field"),
                "The :topic-license: attribute of an external-source topic.");
        field(set, asciidoc, "Topic citation", fqn("AsciiDoc field"),
                "The :topic-citation: attribute of an external-source topic.");
        field(set, asciidoc, "Topic provenance", fqn("AsciiDoc field"),
                "The :topic-provenance: attribute of an external-source topic.");
        field(set, asciidoc, "AsciiDoc reference", ROOT_FQN,
                "Carrying an inline reference or a composition directive: the purpose of the"
                        + " reference patterns and their fields.");

        // ── Patterns ─────────────────────────────────────────────────────────────
        EntityProxy.Concept structure = set.conceptRef(DocumentStructureSet.fqn("Document structure"));
        EntityProxy.Concept reference = set.conceptRef(fqn("AsciiDoc reference"));
        set.pattern(fqn("AsciiDoc document attributes pattern")).at(asciidoc)
                .meaning(set.conceptRef(fqn("AsciiDoc document")))
                .purpose(structure)
                .field(set.conceptRef(fqn("AsciiDoc document title")), structure, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Topic id")), structure, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Topic type")), structure, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Topic status")), structure, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Topic keywords")), structure, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Topic scope note")), structure, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Topic license")), structure, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Topic citation")), structure, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Topic provenance")), structure, KernelTerm.STRING)
                .synonym("AsciiDoc document attributes pattern")
                .definition("A document's title and topic attributes, one version per commit that"
                        + " changed them; absent attributes are empty.");
        reference(set, asciidoc, "AsciiDoc index term reference pattern", "AsciiDoc index term reference", reference,
                "An index term on a line: the text as written and the concept it resolved to.")
                .field(set.conceptRef(fqn("AsciiDoc term text")), reference, KernelTerm.STRING)
                .field(set.conceptRef(fqn("AsciiDoc referenced concept")), reference, KernelTerm.COMPONENT_FIELD);
        reference(set, asciidoc, "AsciiDoc cross reference pattern", "AsciiDoc cross reference", reference,
                "A cross reference on a line: its target anchor and display text.")
                .field(set.conceptRef(fqn("AsciiDoc reference target")), reference, KernelTerm.STRING)
                .field(set.conceptRef(fqn("AsciiDoc reference text")), reference, KernelTerm.STRING);
        reference(set, asciidoc, "AsciiDoc citation pattern", "AsciiDoc citation", reference,
                "A citation on a line: its key and the bibliography entry it resolved to.")
                .field(set.conceptRef(fqn("AsciiDoc citation key")), reference, KernelTerm.STRING)
                .field(set.conceptRef(fqn("AsciiDoc referenced entry")), reference, KernelTerm.COMPONENT_FIELD);
        reference(set, asciidoc, "AsciiDoc footnote pattern", "AsciiDoc footnote", reference,
                "A footnote on a line.")
                .field(set.conceptRef(fqn("AsciiDoc footnote text")), reference, KernelTerm.STRING);
        reference(set, asciidoc, "AsciiDoc link pattern", "AsciiDoc link", reference,
                "A link on a line: its URL and display text.")
                .field(set.conceptRef(fqn("AsciiDoc reference target")), reference, KernelTerm.STRING)
                .field(set.conceptRef(fqn("AsciiDoc reference text")), reference, KernelTerm.STRING);
        reference(set, asciidoc, "AsciiDoc estimate mark pattern", "AsciiDoc estimate mark", reference,
                "An estimate mark on a line, with the note the mark carries.")
                .field(set.conceptRef(fqn("AsciiDoc footnote text")), reference, KernelTerm.STRING);
        reference(set, asciidoc, "AsciiDoc include pattern", "AsciiDoc include", reference,
                "An include directive: its target and verbatim parameters.")
                .field(set.conceptRef(fqn("AsciiDoc reference target")), reference, KernelTerm.STRING)
                .field(set.conceptRef(DocumentStructureSet.fqn("Document element parameters")), reference, KernelTerm.STRING);
        reference(set, asciidoc, "AsciiDoc conditional pattern", "AsciiDoc conditional", reference,
                "A conditional directive: the attribute it tests and whether it is negated.")
                .field(set.conceptRef(fqn("AsciiDoc attribute name")), reference, KernelTerm.STRING)
                .field(set.conceptRef(fqn("AsciiDoc negated")), reference, KernelTerm.BOOLEAN_FIELD);

        // ── Git provenance, in the foundation module: it serves any file, not AsciiDoc alone ──
        set.concept(fqn("Git provenance model")).at(foundation)
                .synonym("Git provenance model")
                .definition("The apparatus that stamps content materialized from a git repository"
                        + " with the repository's own provenance: the homes of the author, module"
                        + " and path concepts an identity adapter derives per repository, and the"
                        + " git source that names the commit a version came from. What people say about"
                        + " those lines is annotation, which serves any component"
                        + " (AnnotationModelSet).")
                .isA(IKE_BASE_MODEL_CONCEPT);
        set.concept(fqn("Git author")).at(foundation)
                .synonym("Git author")
                .definition("The home of author concepts derived from git identities: one per"
                        + " person, keyed by canonical email after mailmap consolidation.")
                .isA(KernelTerm.USER, set.conceptRef(fqn("Git provenance model")));
        set.concept(fqn("Git module")).at(foundation)
                .synonym("Git module")
                .definition("The home of module concepts derived from repositories or Kompendium"
                        + " components: content materialized from a repository stamps in its module.")
                .isA(MODULE_SOLOR, set.conceptRef(fqn("Git provenance model")));
        set.concept(fqn("Git path")).at(foundation)
                .synonym("Git path")
                .definition("The home of path concepts derived from branches: content materialized"
                        + " from a branch stamps on its path.")
                .isA(PATH_SOLOR, set.conceptRef(fqn("Git provenance model")));
        set.concept(fqn("Git provenance")).at(foundation)
                .synonym("Git provenance")
                .definition("Carrying git provenance: the purpose of the git source pattern and its"
                        + " fields.")
                .isA(set.conceptRef(fqn("Git provenance model")));
        set.concept(fqn("Git source")).at(foundation)
                .synonym("Git source")
                .definition("Where a document version came from: the repository-relative path and"
                        + " the commit, one version per commit that changed the file — the bridge"
                        + " from a graph back to git.")
                .isA(set.conceptRef(fqn("Git provenance model")));
        set.concept(fqn("Source path")).at(foundation)
                .synonym("Source path")
                .definition("The file's repository-relative path at the commit.")
                .isA(set.conceptRef(fqn("Git provenance model")));
        set.concept(fqn("Source commit")).at(foundation)
                .synonym("Source commit")
                .definition("The full SHA of the commit a version came from.")
                .isA(set.conceptRef(fqn("Git provenance model")));
        EntityProxy.Concept provenance = set.conceptRef(fqn("Git provenance"));
        set.pattern(fqn("Git source pattern")).at(foundation)
                .meaning(set.conceptRef(fqn("Git source")))
                .purpose(provenance)
                .field(set.conceptRef(fqn("Source path")), provenance, KernelTerm.STRING)
                .field(set.conceptRef(fqn("Source commit")), provenance, KernelTerm.STRING)
                .synonym("Git source pattern")
                .definition("A document's git source: path and commit, one version per commit"
                        + " that changed the file.");
    }

    private static String fqn(String name) {
        return name + " (IkeFoundation)";
    }

    private static void element(KnowledgeSet set, ActiveStamp stamp, String name, String parentFqn, String definition) {
        set.concept(fqn(name)).at(stamp)
                .synonym(name)
                .definition(definition)
                .isA(set.conceptRef(parentFqn));
    }

    private static void field(KnowledgeSet set, ActiveStamp stamp, String name, String parentFqn, String definition) {
        set.concept(fqn(name)).at(stamp)
                .synonym(name)
                .definition(definition)
                .isA(set.conceptRef(parentFqn));
    }

    private static dev.ikm.tinkar.entity.builder.PatternBuilder.ActiveScope reference(KnowledgeSet set, ActiveStamp stamp,
            String patternName, String meaningName, EntityProxy.Concept purpose, String definition) {
        return set.pattern(fqn(patternName)).at(stamp)
                .meaning(set.conceptRef(fqn(meaningName)))
                .purpose(purpose)
                .synonym(patternName)
                .definition(definition);
    }
}
